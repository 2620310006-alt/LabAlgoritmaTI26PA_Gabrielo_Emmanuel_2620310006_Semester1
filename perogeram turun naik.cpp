#include <iostream>

using namespace std;

int main() {
    // Perulangan naik dari 1 sampai 10
    cout << "Contoh Program perulangan" << endl;
    for (int i = 1; i <= 10; i++) {
        cout << i << endl;
    }
    
    cout << endl;
    
    // Perulangan menurun dari 10 sampai 1
    cout << "Perulangan menurun" << endl;
    for (int i = 10; i >= 1; i--) {
        cout << i << endl;
    }
    
    return 0;
}